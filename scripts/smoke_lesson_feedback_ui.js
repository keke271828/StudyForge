const {app, BrowserWindow} = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const casePath = process.env.STUDYFORGE_FEEDBACK_UI_CASE_PATH;
const input = JSON.parse(fs.readFileSync(casePath, 'utf8'));
app.setPath('userData', path.join(path.dirname(casePath), 'electron-profile'));
app.disableHardwareAcceleration();
app.whenReady().then(async () => {
  const win = new BrowserWindow({show:false,width:1400,height:1200,webPreferences:{nodeIntegration:false,contextIsolation:true,sandbox:true,offscreen:true,backgroundThrottling:false}});
  const errors = [];
  win.webContents.on('console-message', event => {if ((event.level === 'error'||event.level===3) && !event.message.includes('404')) errors.push(event.message);});
  try {
    await win.loadURL(input.url);
    await win.webContents.executeJavaScript(`(async () => {
      for(let i=0;i<150 && !(state.ready && state.conversation && !conversationUI.restoring);i++)await new Promise(r=>setTimeout(r,100));
      if(currentLearningMode()!=='deep')throw new Error('默认模式应为精学');
      if([...$('learningMode').options].map(x=>x.value).join(',')!=='overview,deep,research')throw new Error('三种模式缺失');
      $('learningMode').value='research'; $('learningMode').dispatchEvent(new Event('change'));
      await learningModeSave;
      if((await api('/api/settings')).learning_mode!=='research')throw new Error('模式未写入本机设置');
      localStorage.clear(); // A new desktop port has a fresh storage origin.
    })()`);
    await new Promise(resolve => { win.webContents.once('did-finish-load',resolve); win.webContents.reload(); });
    const result = await win.webContents.executeJavaScript(`(async () => {
      const input = ${JSON.stringify(input)};
      const wait = async predicate => { for (let i=0;i<150;i++) {if(await predicate())return;await new Promise(r=>setTimeout(r,100));}throw new Error('UI wait timed out'); };
      await wait(()=>state.project?.id===input.project_id && state.ready && state.conversation && !conversationUI.restoring);
      if(currentLearningMode()!=='research')throw new Error('重开没有保存所选模式');
      await refreshArtifacts();
      await wait(()=>document.querySelector('[data-feedback-job]'));
      if(!document.querySelector('[data-feedback-job]'))throw new Error('成果卡片缺少问卷入口');
      showView('artifacts');
      const first = (await api('/api/projects/'+input.project_id+'/lesson-feedback')).find(x=>x.id===input.submit_id);
      await selectConversation(first.conversation_id);
      applyLearningMode('research');await learningModeSave;await conversationSave;
      await applyExplanationStyle('academic');await applyOutputLanguage('en');
      showView('artifacts');
      document.querySelector('[data-feedback-job="'+first.job_id+'"]').click();
      await wait(()=>document.querySelector('[data-lesson-feedback="'+input.submit_id+'"] form'));
      if(currentLearningMode()!=='research' || currentExplanationStyle()!=='academic' || $('outputLanguage').value!=='en')throw new Error('打开旧问卷改写了后来选择的教学设置');
      const card = document.querySelector('[data-lesson-feedback="'+input.submit_id+'"]');
      if(card.querySelectorAll('input[name=difficulty]').length!==6)throw new Error('困难选项数量错误');
      card.querySelector('[value=prerequisites]').checked=true;
      card.querySelector('[value=motivation]').checked=true;
      card.querySelector('[name=other_text]').value='论证是怎样想到的？<img src=x onerror=alert(1)>';
      if(card.scrollWidth>card.clientWidth+2)throw new Error('问卷横向溢出');
      return {six_options:true,multiselect:true,free_text:true,artifact_entry:true,three_learning_modes:true,mode_persisted:true,newer_teaching_choices_preserved:true};
    })()`);
    const screenshot = path.join(path.dirname(casePath), '理解问卷.png');
    fs.writeFileSync(screenshot,(await win.webContents.capturePage(undefined,{stayHidden:true,stayAwake:true})).toPNG());
    const actions = await win.webContents.executeJavaScript(`(async () => {
      const input = ${JSON.stringify(input)};
      const wait = async predicate => { for(let i=0;i<150;i++){if(await predicate())return;await new Promise(r=>setTimeout(r,100));}throw new Error('UI wait timed out'); };
      document.querySelector('[data-lesson-feedback="'+input.submit_id+'"] form').requestSubmit();
      await wait(async ()=>(await api('/api/projects/'+input.project_id+'/lesson-feedback')).find(x=>x.id===input.submit_id)?.reply_status==='completed' && !state.busy);
      await wait(()=>document.querySelector('[data-lesson-feedback="'+input.submit_id+'"]')?.textContent.includes('补讲已完成'));
      if(currentLearningMode()!=='research' || currentExplanationStyle()!=='academic' || $('outputLanguage').value!=='en')throw new Error('补讲完成后改写了后来选择的教学设置');
      if(document.querySelector('.lesson-questionnaire img'))throw new Error('未转义学生输入');
      const saved = (await api('/api/projects/'+input.project_id+'/lesson-feedback')).find(x=>x.id===input.submit_id);
      if(saved.difficulties.length!==2 || !saved.other_text.includes('onerror'))throw new Error('回答未保存');
      await openLessonFeedback(input.skip_id);
      document.querySelector('[data-feedback-skip="'+input.skip_id+'"]').click();
      await wait(async ()=>(await api('/api/projects/'+input.project_id+'/lesson-feedback')).find(x=>x.id===input.skip_id)?.status==='skipped');
      const memory = await api('/api/profile/memory');
      if(memory.insights.filter(x=>x.kind==='self_report').length!==3 || memory.insights.some(x=>x.kind==='self_report' && !x.confidence.includes('自评')))throw new Error('自评证据错误');
      if(memory.insights.some(x=>String(x.quote||'').includes('onerror')))throw new Error('无关HTML进入学习画像');
      if((await api('/api/profile')).length || (await api('/api/projects/'+input.project_id+'/exercises')).length)throw new Error('问卷触发评分或习题');
      await openLessonFeedback(input.submit_id);
      if(!document.querySelector('[data-lesson-feedback="'+input.submit_id+'"]')?.textContent.includes('补讲已完成'))throw new Error('补讲未恢复');
      const conversation=state.conversation, reading=state.reading.reading_id, scope=materialScope(), model=currentModel();
      $('summaryLevel').value='1';$('summaryLevel').dispatchEvent(new Event('input'));$('withExercises').checked=false;
      $('learningMode').value='research';$('learningMode').dispatchEvent(new Event('change'));
      if(state.conversation!==conversation || state.reading.reading_id!==reading || materialScope()!==scope || currentModel()!==model || $('summaryLevel').value!=='1' || $('withExercises').checked)throw new Error('模式切换改变了对话、缓存或独立选项');
      $('prompt').value='只用原资料简短说明证据与边界，不需要习题。';$('sendMessage').click();
      await wait(()=>!state.busy && !$('prompt').value);
      if(state.conversation!==conversation || state.reading.reading_id!==reading)throw new Error('发送后丢失原对话或通读');
      const before=(await api('/api/projects/'+input.project_id+'/jobs')).map(x=>x.id);
      $('generate').click();
      let generated;
      await wait(async()=>{generated=(await api('/api/projects/'+input.project_id+'/jobs')).find(x=>x.kind==='generate' && !before.includes(x.id));return generated?.status==='completed';});
      const job=await api('/api/jobs/'+generated.id);
      if(job.payload.learning_mode!=='research' || job.payload.summary_level!==1 || job.payload.exercises || job.payload.reading_id!==reading || job.payload.conversation_id!==conversation)throw new Error('实际生成请求模式或独立选项错误');
      const artifact=(await api('/api/projects/'+input.project_id+'/artifacts')).find(x=>x.metadata.generation_job_id===job.id);
      if(artifact?.metadata.learning_mode!=='research')throw new Error('成果未保存模式');
      if((await api('/api/projects/'+input.project_id+'/exercises')).length)throw new Error('研究模式强制出题');
      await wait(()=>!state.busy);
      await learningModeSave;
      showView('study');
      await new Promise(r=>setTimeout(r,150));
      return {supplement_completed:true,answers_persisted:true,escaped_input:true,skip_saved:true,no_score_or_exercises:true,profile_updated:true,dialogue_restored:true,mode_keeps_dialogue_and_reading:true,controls_independent:true,chat_and_generation:true,mode_recorded_in_artifact:true};
    })()`);
    if(errors.length)throw new Error(errors.join('; '));
    const modeScreenshot=path.join(path.dirname(casePath),'学习模式.png');
    fs.writeFileSync(modeScreenshot,(await win.webContents.capturePage(undefined,{stayHidden:true,stayAwake:true})).toPNG());
    console.log(JSON.stringify({ok:true,result,actions,screenshot,modeScreenshot,console_errors:errors}));
    win.destroy();app.quit();
  } catch(error) {console.error(error);win.destroy();app.exit(1);}
});

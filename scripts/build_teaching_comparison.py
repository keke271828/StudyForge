def inline_script(text):
    return re.sub(r'</script', r'<\\/script', text, flags=re.I)


def build(args):
    groups, total, failures = [], 0, []
    review_path = getattr(args, 'reviews', None)
    notes = json.loads(Path(review_path).read_text(encoding='utf-8')) if review_path else {}
    for argument in args.report:
        label, separator, location = argument.partition('=')
        if not separator:
            raise ValueError('--report must be Label=path/to/report.json')
        report_path = Path(location).resolve()
        packet = json.loads(report_path.read_text(encoding='utf-8'))
        for case in dict.fromkeys(row['case'] for row in packet['results']):
            rows = []
            for row in packet['results']:
                if row['case'] != case:
                    continue
                if row['status'] != 'completed':
                    failures.append({'round': label, **row})
                    continue
                output = Path(row['output'])
                request = report_path.parent / f'{case}-{row["arm"]}-request.json'
                # Keep the actual saved bytes, including Windows newlines, so
                # the downloadable text and its fingerprint match the file.
                text = output.read_bytes().decode('utf-8')
                rows.append({**row, 'label': ARM_LABELS[row['arm']], 'text': text,
                             'sha256': hashlib.sha256(text.encode()).hexdigest(),
                             'request': json.loads(request.read_text(encoding='utf-8')),
                             'review': notes.get(label, {}).get(case, {}).get(row['arm']) or review(label, case, row['arm'])})
            # Stable, concealed order independent of which arm is original.
            rows.sort(key=lambda row: row['sha256'])
            if not rows:
                continue
            total += len(rows)
            groups.append({'round': label, 'case': case, 'title': CASES[case]['title'],
                           'question': CASES[case]['question'], 'source': CASES[case]['source'],
                           'settings': packet['settings'], 'rows': rows})
    if not groups:
        raise ValueError('No completed outputs; a failed request is not a model answer.')
    payload = json.dumps({'groups': groups, 'count': total, 'failures': failures}, ensure_ascii=False).replace('<', '\\u003c')
    assets = ROOT / 'web' / 'vendor'
    css = (assets / 'katex.css').read_text(encoding='utf-8')
    def font(match):
        encoded = base64.b64encode((assets / 'fonts' / match[1]).read_bytes()).decode()
        return f'url(data:font/woff2;base64,{encoded})'
    css = re.sub(r'url\(fonts/([^)]*\.woff2)\)', font, css)
    # The WOFF2 face is embedded; omit redundant fallbacks to keep this offline.
    css = re.sub(r',url\(fonts/[^)]*\) format\("(?:woff|truetype)"\)', '', css)
    libraries = '\n'.join(inline_script((assets / name).read_text(encoding='utf-8'))
                          for name in ['marked.js', 'purify.js', 'katex.js'])
    renderer = inline_script((ROOT / 'web' / 'lesson_render.js').read_text(encoding='utf-8'))
    html = TEMPLATE.replace('__KATEX_CSS__', css).replace('__PAYLOAD__', payload)
    html = html.replace('__LIBRARIES__', libraries).replace('__RENDERER__', renderer)
    target = Path(args.output).resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(html, encoding='utf-8')
    manifest = {'samples': total, 'failed_requests': len(failures), 'groups': len(groups), 'output': str(target),
                'bytes': target.stat().st_size, 'model_calls': 0,
                'scope': 'API outputs only; website connection pending; offline review page'}
    target.with_suffix('.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps(manifest, ensure_ascii=False))


